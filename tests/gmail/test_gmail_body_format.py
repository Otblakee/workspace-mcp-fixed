class TestHtmlFormat:
    @pytest.mark.asyncio
    async def test_a_plain_only_falls_back_with_note(self):
        out = await get_message(
            fx.FakeGmailService(), "m-plain", USER, body_format="html"
        )
        section = _html_section(out)
        assert gmail_tools.NO_HTML_PART_NOTE in section
        assert fx.PLAIN_TEXT.strip() in section
        assert "<html" not in section
        # Header lines unchanged from the text path.
        assert out.startswith(GOLDENS["single"]["m-plain"].split("--- BODY ---")[0])

    @pytest.mark.asyncio
    async def test_b_alternative_returns_html_part_with_img_srcs(self):
        out = await get_message(
            fx.FakeGmailService(), "m-alt", USER, body_format="html"
        )
        section = _html_section(out)
        assert fx.ALT_HTML in section
        assert fx.ALT_TEXT not in section
        assert gmail_tools.NO_HTML_PART_NOTE not in section
        assert "Images (<img src>): 2" in section
        assert "  1. https://cdn.example.com/bir-logo.png" in section
        assert "  2. https://cdn.example.com/frame-artwork.png" in section
        assert "Inline cid: references: 0" in section

    @pytest.mark.asyncio
    async def test_c_mixed_related_cid_maps_to_attachment(self):
        out = await get_message(
            fx.FakeGmailService(), "m-mixed", USER, body_format="html"
        )
        section = _html_section(out)
        assert fx.RELATED_HTML in section
        assert "Images (<img src>): 2" in section
        assert "  1. cid:logo@bir" in section
        assert "  2. https://cdn.example.com/frame-artwork.png" in section
        assert "Inline cid: references: 1" in section
        assert (
            "cid:logo@bir -> BIR Logo.png (image/png), attachmentId: ATT-LOGO"
            in section
        )
        assert (
            "get_gmail_attachment_content(message_id='m-mixed', attachment_id='ATT-LOGO')"
            in section
        )
        # The attachments section is still appended after the body.
        assert "--- ATTACHMENTS ---" in out
        assert "quote.pdf" in out

    @pytest.mark.asyncio
    async def test_d_html_under_attachment_id_is_fetched(self):
        svc = fx.FakeGmailService()
        out = await get_message(svc, "m-htmlatt", USER, body_format="html")
        section = _html_section(out)
        assert fx.BIG_HTML in section
        assert gmail_tools.NO_HTML_PART_NOTE not in section
        assert (
            "attachments.get",
            {"messageId": "m-htmlatt", "id": "ATT-HTML"},
        ) in svc.calls

    @pytest.mark.asyncio
    async def test_e_raw_fixture_html_path_still_returns_html(self):
        out = await get_message(
            fx.FakeGmailService(), "m-raw", USER, body_format="html"
        )
        assert fx.ALT_HTML in _html_section(out)

    @pytest.mark.asyncio
    async def test_batch_html_per_message(self):
        out = await get_batch(
            fx.FakeGmailService(),
            ["m-plain", "m-alt", "m-mixed"],
            USER,
            body_format="html",
        )
        assert out.count(gmail_tools.HTML_BODY_SECTION_HEADER) == 3
        assert out.count(gmail_tools.NO_HTML_PART_NOTE) == 1  # only the plain one
        assert fx.ALT_HTML in out
        assert fx.RELATED_HTML in out
        assert "cid:logo@bir -> BIR Logo.png (image/png), attachmentId: ATT-LOGO" in out
        # The existing `format` parameter still drives the request type.
        assert "Web Link: https://mail.google.com/mail/u/0/#all/m-alt" in out

    @pytest.mark.asyncio
    async def test_thread_html_per_message(self):
        svc = fx.FakeGmailService()
        out = await get_thread(svc, "t1", USER, body_format="html")
        assert out.startswith("Thread ID: t1\nSubject: Signature test\nMessages: 4\n")
        assert out.count(gmail_tools.HTML_BODY_SECTION_HEADER) == 4
        assert out.count(gmail_tools.NO_HTML_PART_NOTE) == 1
        assert fx.ALT_HTML in out
        assert fx.RELATED_HTML in out
        assert fx.BIG_HTML in out
        assert ("threads.get", {"id": "t1", "format": "full"}) in svc.calls
        assert (
            "attachments.get",
            {"messageId": "m-htmlatt", "id": "ATT-HTML"},
        ) in svc.calls

    @pytest.mark.asyncio
    async def test_html_body_is_capped_at_one_megabyte(self):
        big = (
            "<html><body>"
            + "x" * (gmail_tools.RAW_BODY_MAX_BYTES + 100)
            + "</body></html>"
        )
        payload = {
            "mimeType": "text/html",
            "filename": "",
            "headers": [],
            "body": {"size": len(big), "data": fx.b64url(big)},
        }
        msg = fx._msg("m-big", payload)
        svc = fx.FakeGmailService(messages={"m-big": msg})
        out = await get_message(svc, "m-big", USER, body_format="html")
        assert (
            f"[HTML body truncated: showing first {gmail_tools.RAW_BODY_MAX_BYTES:,} of"
            in out
        )
        assert len(out.encode("utf-8")) < gmail_tools.RAW_BODY_MAX_BYTES + 2000


class TestHtmlPartSelection:
    """_find_html_part prefers the html part sitting beside the text/plain part."""

    def test_prefers_sibling_of_text_plain(self):
        quoted_html = fx._part("text/html", "<p>forwarded</p>", part_id="1.0.1")
        payload = fx._part(
            "multipart/mixed",
            parts=[
                fx._part(
                    "multipart/alternative",
                    part_id="0",
                    parts=[
                        fx._part("text/plain", "body", part_id="0.0"),
                        fx._part("text/html", "<p>body</p>", part_id="0.1"),
                    ],
                ),
                fx._part(
                    "message/rfc822",
                    part_id="1",
                    parts=[
                        fx._part(
                            "multipart/alternative", part_id="1.0", parts=[quoted_html]
                        )
                    ],
                ),
            ],
        )
        # Put the nested one first in document order to prove preference wins over order.
        payload["parts"].reverse()
        chosen = gmail_tools._find_html_part(payload)
        assert chosen["partId"] == "0.1"

    def test_falls_back_to_first_html_in_document_order(self):
        payload = fx._part(
            "multipart/related",
            parts=[
                fx._part("text/html", "<p>first</p>", part_id="0"),
                fx._part("text/html", "<p>second</p>", part_id="1"),
            ],
        )
        assert gmail_tools._find_html_part(payload)["partId"] == "0"

    def test_attached_html_file_is_not_the_body(self):
        payload = fx._part(
            "multipart/mixed",
            parts=[
                fx._part("text/plain", "see attached", part_id="0"),
                fx._part(
                    "text/html",
                    attachment_id="ATT-FILE",
                    filename="report.html",
                    part_id="1",
                    headers=fx._headers(
                        Content_Disposition='attachment; filename="report.html"'
                    ),
                ),
            ],
        )
        assert gmail_tools._find_html_part(payload) is None

    def test_root_level_html_only_message(self):
        payload = fx._part("text/html", "<p>hi</p>")
        assert gmail_tools._find_html_part(payload) is payload

    def test_cid_index_strips_angle_brackets_and_reads_x_attachment_id(self):
        index = gmail_tools._cid_part_index(fx.MIXED["payload"])
        assert index["logo@bir"]["attachmentId"] == "ATT-LOGO"
        assert index["logo@bir"]["filename"] == "BIR Logo.png"

    def test_reference_block_reports_unmatched_cid(self):
        html = '<img src="cid:missing@x"><div style="background:url(cid:also@x)"></div>'
        block = gmail_tools._html_reference_block(html, fx.PLAIN["payload"], "m")
        assert "Images (<img src>): 1" in block
        assert "Inline cid: references: 2" in block
        assert "cid:missing@x -> (no matching part found)" in block
        assert "cid:also@x -> (no matching part found)" in block

    def test_charset_is_honoured(self):
        latin = "café".encode("latin-1")
        part = {
            "mimeType": "text/html",
            "headers": [
                {"name": "Content-Type", "value": "text/html; charset=ISO-8859-1"}
            ],
            "body": {"data": fx.b64url(latin)},
        }
        assert gmail_tools._decode_part_bytes(part, latin) == "café"


