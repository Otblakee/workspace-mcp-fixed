class TestRawFormat:
    @pytest.mark.asyncio
    async def test_e_single_raw_returns_rfc2822_source(self):
        svc = fx.FakeGmailService()
        out = await get_message(svc, "m-raw", USER, body_format="raw")
        assert gmail_tools.RAW_BODY_SECTION_HEADER in out
        body = out.split(gmail_tools.RAW_BODY_SECTION_HEADER, 1)[1]
        assert body.strip() == fx.RAW_SOURCE.strip()
        assert 'Content-Type: multipart/alternative; boundary="b1"' in body
        # Header block is still taken from the metadata call, as before.
        assert out.startswith(GOLDENS["single"]["m-raw"].split("--- BODY ---")[0])
        assert svc.calls == [
            ("messages.get", {"id": "m-raw", "format": "metadata"}),
            ("messages.get", {"id": "m-raw", "format": "raw"}),
        ]
        assert "truncated" not in out

    @pytest.mark.asyncio
    async def test_single_raw_truncates_at_one_megabyte_and_states_size(self):
        big = "Subject: big\r\n\r\n" + "y" * (gmail_tools.RAW_BODY_MAX_BYTES + 5000)
        svc = fx.FakeGmailService(raw_sources={"m-raw": big})
        out = await get_message(svc, "m-raw", USER, body_format="raw")
        total = len(big.encode("utf-8"))
        assert (
            f"[raw source truncated: showing first {gmail_tools.RAW_BODY_MAX_BYTES:,} of {total:,} bytes]"
            in out
        )
        assert len(out.encode("utf-8")) < gmail_tools.RAW_BODY_MAX_BYTES + 1000

    @pytest.mark.asyncio
    async def test_batch_raw_uses_format_raw_and_parses_headers(self):
        svc = fx.FakeGmailService()
        out = await get_batch(svc, ["m-raw"], USER, body_format="raw")
        assert svc.calls == [("messages.get", {"id": "m-raw", "format": "raw"})]
        assert (
            "Message ID: m-raw\nSubject: Signature test\nFrom: Oli Blake <oliver@otbgroup.co.uk>\n"
            in out
        )
        assert "Date: Wed, 5 Nov 2026 09:00:00 +0000" in out
        assert "Message-ID: <sig-test@otbgroup.co.uk>" in out
        assert gmail_tools.RAW_BODY_SECTION_HEADER in out
        assert fx.RAW_SOURCE.strip() in out

    @pytest.mark.asyncio
    async def test_batch_raw_sequential_fallback_also_uses_format_raw(self):
        svc = fx.FakeGmailService()

        def broken_batch(callback=None):
            raise RuntimeError("batch unavailable")

        svc.new_batch_http_request = broken_batch
        out = await get_batch(svc, ["m-raw"], USER, body_format="raw")
        assert svc.calls == [("messages.get", {"id": "m-raw", "format": "raw"})]
        assert fx.RAW_SOURCE.strip() in out

    @pytest.mark.asyncio
    async def test_thread_raw_fetches_each_message_raw(self):
        svc = fx.FakeGmailService(threads={"t-raw": ["m-raw", "m-alt"]})
        out = await get_thread(svc, "t-raw", USER, body_format="raw")
        assert svc.calls[0] == ("threads.get", {"id": "t-raw", "format": "metadata"})
        assert ("messages.get", {"id": "m-raw", "format": "raw"}) in svc.calls
        assert ("messages.get", {"id": "m-alt", "format": "raw"}) in svc.calls
        assert not any(c[1].get("format") == "full" for c in svc.calls)
        assert out.startswith(
            "Thread ID: t-raw\nSubject: Signature test\nMessages: 2\n"
        )
        assert out.count(gmail_tools.RAW_BODY_SECTION_HEADER) == 2
        assert (
            "From: Oli Blake <oliver@otbgroup.co.uk>\nDate: Wed, 5 Nov 2026 09:00:00 +0000"
            in out
        )


