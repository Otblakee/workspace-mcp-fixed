"""body_format on the Gmail read tools (v1.18.0).

Three tools gain an optional ``body_format`` parameter: ``get_gmail_message_content``,
``get_gmail_messages_content_batch`` and ``get_gmail_thread_content``.

- ``"text"`` (default) must be byte-identical to the pre-change output. The
  goldens in ``body_format_goldens.json`` were generated by running the three
  tools from commit 4cea3dd (before this change) over the fixture payloads in
  ``body_format_fixtures.py``. Every test here compares against those strings,
  both with ``body_format="text"`` spelled out and with the parameter omitted.
- ``"html"`` returns the text/html part found by walking the whole MIME tree,
  preceded by a header block of ``<img src>`` URLs and ``cid:`` references.
- ``"raw"`` returns the decoded RFC 2822 source from ``format=raw``.

Fixture cases, per the task: (a) plain text only, (b) multipart/alternative,
(c) multipart/mixed > multipart/related with a cid image, (d) html stored under
attachmentId, (e) raw. The Gmail service is a fake; nothing touches the network.
"""

from __future__ import annotations

import inspect
import json
from pathlib import Path

import pytest

from core.utils import UserInputError
from gmail import gmail_tools

from . import body_format_fixtures as fx

GOLDENS = json.loads(
    (Path(__file__).parent / "body_format_goldens.json").read_text(encoding="utf-8")
)
USER = fx.USER


def _unwrap(fn):
    while hasattr(fn, "__wrapped__"):
        fn = fn.__wrapped__
    return fn


get_message = _unwrap(gmail_tools.get_gmail_message_content)
get_batch = _unwrap(gmail_tools.get_gmail_messages_content_batch)
get_thread = _unwrap(gmail_tools.get_gmail_thread_content)

CASES = {
    "a_plain": "m-plain",
    "b_alternative": "m-alt",
    "c_mixed_related_cid": "m-mixed",
    "d_html_under_attachment_id": "m-htmlatt",
    "e_raw": "m-raw",
}


def _html_section(output: str) -> str:
    assert gmail_tools.HTML_BODY_SECTION_HEADER in output
    return output.split(gmail_tools.HTML_BODY_SECTION_HEADER, 1)[1]


