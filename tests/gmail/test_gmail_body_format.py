class TestParameterSurface:
    @pytest.mark.asyncio
    @pytest.mark.parametrize("tool", [get_message, get_batch, get_thread])
    async def test_unknown_body_format_refused_before_any_call(self, tool):
        svc = fx.FakeGmailService()
        args = (["m-alt"],) if tool is get_batch else ("m-alt",)
        with pytest.raises(UserInputError):
            await tool(svc, *args, USER, body_format="markdown")
        assert svc.calls == []

    def test_default_is_text_on_all_three(self):
        for fn in (get_message, get_batch, get_thread):
            assert inspect.signature(fn).parameters["body_format"].default == "text"

    def test_batch_keeps_format_parameter(self):
        params = inspect.signature(get_batch).parameters
        assert list(params)[:4] == [
            "service",
            "message_ids",
            "user_google_email",
            "format",
        ]
        assert params["format"].default == "full"

    def test_mcp_schema_exposes_body_format_enum(self):
        from core.server import server
        from core.tool_registry import get_tool_components

        components = get_tool_components(server)
        for name in (
            "get_gmail_message_content",
            "get_gmail_messages_content_batch",
            "get_gmail_thread_content",
        ):
            prop = components[name].parameters["properties"]["body_format"]
            assert prop["enum"] == ["text", "html", "raw"], name
            assert prop["default"] == "text", name
            assert "description" in prop and "html" in prop["description"], name
        batch_props = components["get_gmail_messages_content_batch"].parameters[
            "properties"
        ]
        assert batch_props["format"]["enum"] == ["full", "metadata"]
