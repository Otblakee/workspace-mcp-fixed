class TestTextPathUnchanged:
    @pytest.mark.asyncio
    @pytest.mark.parametrize("case", sorted(CASES), ids=sorted(CASES))
    async def test_single_default_matches_golden(self, case):
        mid = CASES[case]
        assert (
            await get_message(fx.FakeGmailService(), mid, USER)
            == GOLDENS["single"][mid]
        )

    @pytest.mark.asyncio
    @pytest.mark.parametrize("case", sorted(CASES), ids=sorted(CASES))
    async def test_single_explicit_text_matches_golden(self, case):
        mid = CASES[case]
        out = await get_message(fx.FakeGmailService(), mid, USER, body_format="text")
        assert out == GOLDENS["single"][mid]

    @pytest.mark.asyncio
    @pytest.mark.parametrize("case", sorted(CASES), ids=sorted(CASES))
    async def test_batch_default_and_text_match_golden(self, case):
        mid = CASES[case]
        assert (
            await get_batch(fx.FakeGmailService(), [mid], USER) == GOLDENS["batch"][mid]
        )
        out = await get_batch(fx.FakeGmailService(), [mid], USER, body_format="text")
        assert out == GOLDENS["batch"][mid]

    @pytest.mark.asyncio
    async def test_batch_all_messages_matches_golden(self):
        ids = list(fx.ALL_MESSAGES)
        assert (
            await get_batch(fx.FakeGmailService(), ids, USER)
            == GOLDENS["batch"]["__all__"]
        )

    @pytest.mark.asyncio
    @pytest.mark.parametrize("case", sorted(CASES), ids=sorted(CASES))
    async def test_batch_metadata_matches_golden(self, case):
        mid = CASES[case]
        out = await get_batch(fx.FakeGmailService(), [mid], USER, format="metadata")
        assert out == GOLDENS["batch_metadata"][mid]

    @pytest.mark.asyncio
    @pytest.mark.parametrize("body_format", ["html", "raw"])
    async def test_batch_metadata_ignores_body_format(self, body_format):
        """format="metadata" has no body, so body_format changes nothing and
        no raw or attachment fetch is made."""
        svc = fx.FakeGmailService()
        out = await get_batch(
            svc, ["m-mixed"], USER, format="metadata", body_format=body_format
        )
        assert out == GOLDENS["batch_metadata"]["m-mixed"]
        assert all(call[1].get("format") == "metadata" for call in svc.calls)

    @pytest.mark.asyncio
    @pytest.mark.parametrize("tid", ["t1", "t-raw"])
    async def test_thread_default_and_text_match_golden(self, tid):
        assert (
            await get_thread(fx.FakeGmailService(), tid, USER) == GOLDENS["thread"][tid]
        )
        out = await get_thread(fx.FakeGmailService(), tid, USER, body_format="text")
        assert out == GOLDENS["thread"][tid]

    @pytest.mark.asyncio
    async def test_text_path_makes_no_extra_calls(self):
        """The text path hits exactly the endpoints it did before: metadata then
        full for the single tool, never attachments.get or format=raw."""
        svc = fx.FakeGmailService()
        await get_message(svc, "m-htmlatt", USER)
        assert svc.calls == [
            ("messages.get", {"id": "m-htmlatt", "format": "metadata"}),
            ("messages.get", {"id": "m-htmlatt", "format": "full"}),
        ]

    def test_text_helpers_untouched_signatures(self):
        """The helpers the text path uses keep their public shape."""
        assert list(
            inspect.signature(gmail_tools._extract_message_bodies).parameters
        ) == ["payload"]
        assert list(inspect.signature(gmail_tools._format_body_content).parameters) == [
            "text_body",
            "html_body",
        ]


